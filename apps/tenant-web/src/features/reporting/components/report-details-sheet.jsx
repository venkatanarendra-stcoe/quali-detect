import { RefreshCw, Trash2 } from "lucide-react";
import { QueryErrorState } from "@/components/states/error-state.jsx";
import { Button } from "@/components/ui/button.jsx";
import { Sheet, SheetContent, SheetDescription, SheetTitle } from "@/components/ui/sheet.jsx";
import { Skeleton } from "@/components/ui/skeleton.jsx";
import {
  Identifier,
  absoluteTime,
  formatDuration,
} from "@/features/executions/components/execution-bits.jsx";
import { REPORT_FAILURE_TEXT } from "../constants/index.js";
import { useReturnFocus } from "../hooks/use-return-focus.js";
import { useReport } from "../hooks/use-reporting.js";
import { formatBytes, formatCount } from "../schemas/format.js";
import { DownloadButton } from "./reports-table.jsx";
import { ReportStatusChip, periodText, templateTitle } from "./report-bits.jsx";

const when = (value) =>
  value ? absoluteTime(value, { dateStyle: "medium", timeStyle: "medium" }) : "—";

function Row({ label, children }) {
  return (
    <div className="grid grid-cols-[8rem_1fr] gap-2 border-b border-border py-2 text-sm">
      <dt className="text-muted-foreground">{label}</dt>
      <dd className="min-w-0">{children}</dd>
    </div>
  );
}

/**
 * T-51 Report details. Facts about the run only; no preview of the content (a preview would be a second render path). The SHA-256
 * of the file is not part of the response contract of this version, so it is not shown.
 * @param {{ workspaceId: string, workspaceName?: string, reportId: string | null, onClose: () => void, onDownload: (id: string) => void, downloading: boolean,
 *   canDelete: (report: any) => boolean, onDelete: (report: any) => void, onAgain: (report: any) => void, canExport: boolean }} props
 */
export function ReportDetailsSheet({
  workspaceId,
  workspaceName,
  reportId,
  onClose,
  onDownload,
  downloading,
  canDelete,
  onDelete,
  onAgain,
  canExport,
}) {
  const returnFocus = useReturnFocus();
  const query = useReport(workspaceId, reportId);
  const r = query.data;
  const duration =
    r?.startedAt && r.finishedAt ? new Date(r.finishedAt) - new Date(r.startedAt) : null;
  return (
    <Sheet open={Boolean(reportId)} onOpenChange={(open) => !open && onClose()}>
      <SheetContent data-testid="report-details" {...returnFocus}>
        <SheetTitle className="text-base font-semibold">
          {r ? templateTitle(r.template) : "Report details"}
        </SheetTitle>
        <SheetDescription className="text-sm text-muted-foreground">
          Facts about this report run.
        </SheetDescription>
        {query.isPending ? (
          <div role="status" aria-busy="true">
            <span className="sr-only">Loading report…</span>
            <Skeleton className="h-48 w-full" />
          </div>
        ) : null}
        {query.isError ? <QueryErrorState error={query.error} onRetry={query.refetch} /> : null}
        {r ? (
          <>
            <dl>
              <Row label="Status">
                <ReportStatusChip status={r.status} />
              </Row>
              {r.status === "failed" ? (
                <Row label="Reason">
                  <span className="font-mono text-xs">{r.errorCode}</span>
                  <p className="mt-1">
                    {REPORT_FAILURE_TEXT[r.errorCode] ?? "The report could not be built."}
                  </p>
                </Row>
              ) : null}
              <Row label="Template">{templateTitle(r.template)}</Row>
              <Row label="Scope">
                {r.workspaceId ? (workspaceName ?? "This workspace") : "Entire organization"}
              </Row>
              <Row label="Period">{periodText(r)}</Row>
              <Row label="Format">
                <span className="font-mono text-xs">{r.format.toUpperCase()}</span>
              </Row>
              <Row label="Generated by">
                <span className="block truncate" title={r.requestedBy.displayName}>
                  {r.requestedBy.displayName}
                </span>
              </Row>
              <Row label="Created">{when(r.createdAt)}</Row>
              <Row label="Started">{when(r.startedAt)}</Row>
              <Row label="Finished">{when(r.finishedAt)}</Row>
              <Row label="Duration">{duration === null ? "—" : formatDuration(duration)}</Row>
              <Row label="Size">{formatBytes(r.bytes)}</Row>
              <Row label="Rows">{r.rowCount === null ? "—" : formatCount(r.rowCount)}</Row>
              <Row label="Report id">
                <Identifier value={r.id} max={9} copy label="report id" />
              </Row>
            </dl>
            <div className="flex flex-wrap items-start gap-2">
              <DownloadButton report={r} onDownload={onDownload} pending={downloading} />
              {canExport ? (
                <Button variant="secondary" size="sm" onClick={() => onAgain(r)}>
                  <RefreshCw aria-hidden="true" />
                  Generate again with the same options
                </Button>
              ) : null}
              {canDelete(r) ? (
                <Button variant="ghost" size="sm" onClick={() => onDelete(r)}>
                  <Trash2 aria-hidden="true" />
                  Delete
                </Button>
              ) : null}
            </div>
          </>
        ) : null}
      </SheetContent>
    </Sheet>
  );
}
