import { REPORT_TEMPLATES } from "@qmentisai/shared";
import { Download, Info, Trash2 } from "lucide-react";
import { createContext, useContext } from "react";
import { QueryTable } from "@/components/common/query-table.jsx";
import { Button } from "@/components/ui/button.jsx";
import { TimeAgo } from "@/features/executions/components/execution-bits.jsx";
import { REPORT_FAILURE_TEXT } from "../constants/index.js";
import { formatBytes } from "../schemas/format.js";
import { ReportStatusChip, availableUntil, periodText, templateTitle } from "./report-bits.jsx";

/** The download button with its expiry hint; Ready reports only. The file is fetched by an authenticated request (never a link). */
export function DownloadButton({ report, onDownload, pending }) {
  if (report.status !== "ready" || !report.canDownload) return null;
  return (
    <div className="flex flex-col items-start gap-0.5">
      <Button
        variant="secondary"
        size="sm"
        disabled={pending}
        onClick={() => onDownload(report.id)}
        aria-label={`Download ${templateTitle(report.template)} (${report.format.toUpperCase()})`}
      >
        <Download aria-hidden="true" />
        Download
      </Button>
      <span className="text-xs text-muted-foreground">{availableUntil(report.expiresAt)}</span>
    </div>
  );
}

/**
 * The handlers and names the cells need. The columns below are built ONCE at module level with component cells that read this
 * context, because a new cell function per render would remount every cell on each poll and drop the keyboard focus.
 */
const TableContext = createContext(/** @type {any} */ (null));

function ReportCell({ report: r }) {
  return (
    <div className="min-w-40">
      <p className="font-medium">{templateTitle(r.template)}</p>
      {r.status === "failed" ? (
        <p className="text-xs text-status-danger">
          {REPORT_FAILURE_TEXT[r.errorCode] ?? "The report could not be built."}
        </p>
      ) : null}
      {r.status === "expired" ? (
        <p className="text-xs text-muted-foreground">Expired. Generate again.</p>
      ) : null}
    </div>
  );
}
function ScopeCell({ report: r }) {
  const { workspaceName } = useContext(TableContext);
  if (!r.workspaceId) return "Entire organization";
  return (
    <span className="block max-w-40 truncate" title={workspaceName}>
      {workspaceName ?? "Workspace"}
    </span>
  );
}
const PeriodCell = ({ report: r }) => <span className="whitespace-nowrap">{periodText(r)}</span>;
const FormatCell = ({ report: r }) => (
  <span className="font-mono text-xs">{r.format.toUpperCase()}</span>
);
const ByCell = ({ report: r }) => (
  <span className="block max-w-36 truncate" title={r.requestedBy.displayName}>
    {r.requestedBy.displayName}
  </span>
);
const CreatedCell = ({ report: r }) => <TimeAgo value={r.createdAt} />;
const StatusCell = ({ report: r }) => <ReportStatusChip status={r.status} />;
const SizeCell = ({ report: r }) => (
  <span className="tabular-nums">{r.status === "ready" ? formatBytes(r.bytes) : "—"}</span>
);
function DownloadCell({ report: r }) {
  const { onDownload, downloadingId } = useContext(TableContext);
  return <DownloadButton report={r} onDownload={onDownload} pending={downloadingId === r.id} />;
}
function ActionsCell({ report: r }) {
  const { onOpen, canDelete, onDelete } = useContext(TableContext);
  return (
    <div className="flex items-center gap-1">
      <Button
        variant="ghost"
        size="icon"
        aria-label={`Details of ${templateTitle(r.template)}, ${r.format.toUpperCase()}`}
        onClick={() => onOpen(r.id)}
      >
        <Info aria-hidden="true" />
      </Button>
      {canDelete(r) ? (
        <Button
          variant="ghost"
          size="icon"
          aria-label={`Delete ${templateTitle(r.template)}, ${r.format.toUpperCase()}`}
          onClick={() => onDelete(r)}
        >
          <Trash2 aria-hidden="true" />
        </Button>
      ) : null}
    </div>
  );
}

const column = (id, header, Cell) => ({
  id,
  header,
  accessorFn: () => null,
  cell: ({ row }) => <Cell report={row.original} />,
});
const COLUMNS = [
  column("report", "Report", ReportCell),
  column("scope", "Scope", ScopeCell),
  column("period", "Period", PeriodCell),
  column("format", "Format", FormatCell),
  column("by", "Generated by", ByCell),
  column("created", "Created", CreatedCell),
  column("status", "Status", StatusCell),
  column("size", "Size", SizeCell),
  column("download", "Download", DownloadCell),
  column("actions", "Actions", ActionsCell),
];

/**
 * The generated-reports table (T-39). Failed rows show the stable reason, expired rows say "Expired. Generate again." Details opens
 * the sheet; Delete is offered to the requester and to `report.export` holders (`canDelete`). The API gives a cursor, so the table
 * pages with "Load more".
 * @param {{ list: any, rows: any[], workspaceName?: string, onOpen: (id: string) => void, onDownload: (id: string) => void,
 *   downloadingId?: string | null, canDelete: (report: any) => boolean, onDelete: (report: any) => void, emptyState: any }} props
 */
export function ReportsTable({
  list,
  rows,
  workspaceName,
  onOpen,
  onDownload,
  downloadingId,
  canDelete,
  onDelete,
  emptyState,
}) {
  return (
    <TableContext.Provider
      value={{ workspaceName, onOpen, onDownload, downloadingId, canDelete, onDelete }}
    >
      <QueryTable
        query={list}
        items={rows}
        columns={COLUMNS}
        caption="Generated reports"
        getRowId={(r) => r.id}
        emptyState={emptyState}
        hasMore={list.hasMore}
        loadingMore={list.loadingMore}
        onLoadMore={list.loadMore}
        height="auto"
        maxHeight="36rem"
        noun="reports"
      />
    </TableContext.Provider>
  );
}

export const TEMPLATE_FILTER_OPTIONS = REPORT_TEMPLATES.filter((t) => t.v1).map((t) => ({
  value: t.id,
  label: t.title,
}));
