-- ---- 1. foreign keys between findings and their open decision requests -----------------------------------------------------------
-- A finding points at its pending review, its pending exception and its active exception while each of those rows points back at the
-- finding: the pointers are deferred so one transaction can create both in any order and the tenant purge can delete them together.
