-- ---- 16. retention purge functions (SPEC 7.6; the only way to DELETE from an immutable table) ------------------------------------------
-- SECURITY DEFINER with a fixed search_path; they set `qm.purge` = 'on' for their own transaction and reset it. EXECUTE is not granted
-- to PUBLIC. Each returns the number of rows touched.
CREATE FUNCTION qm_findings_purge_snippets(p_cutoff timestamptz, p_limit integer) RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE n integer;
BEGIN
  -- the snippet of a closed finding is dropped 90 days after it closed; the link and the line numbers stay (SPEC 7.6)
  WITH doomed AS (
    SELECT e."tenant_id", e."finding_id" FROM "finding_evidence" e
    JOIN "findings" f ON f."tenant_id" = e."tenant_id" AND f."id" = e."finding_id"
    WHERE e."snippet" IS NOT NULL AND f."status" IN ('verified_fixed', 'false_positive', 'suppressed') AND f."closed_at" IS NOT NULL AND f."closed_at" < p_cutoff
    LIMIT p_limit)
  UPDATE "finding_evidence" e SET "snippet" = NULL, "snippet_purged_at" = now() FROM doomed d WHERE e."tenant_id" = d."tenant_id" AND e."finding_id" = d."finding_id";
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END;
$$;

CREATE FUNCTION qm_findings_purge_advisories(p_cutoff timestamptz, p_limit integer) RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE n integer;
BEGIN
  PERFORM set_config('qm.purge', 'on', true);
  WITH doomed AS (
    SELECT a."tenant_id", a."id" FROM "finding_ai_advisories" a
    JOIN "findings" f ON f."tenant_id" = a."tenant_id" AND f."id" = a."finding_id"
    WHERE f."status" IN ('verified_fixed', 'false_positive', 'suppressed') AND f."closed_at" IS NOT NULL AND f."closed_at" < p_cutoff
    LIMIT p_limit)
  DELETE FROM "finding_ai_advisories" a USING doomed d WHERE a."tenant_id" = d."tenant_id" AND a."id" = d."id";
  GET DIAGNOSTICS n = ROW_COUNT;
  PERFORM set_config('qm.purge', 'off', true);
  RETURN n;
END;
$$;

CREATE FUNCTION qm_findings_purge_ingestions(p_cutoff timestamptz, p_limit integer) RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE n integer;
BEGIN
  PERFORM set_config('qm.purge', 'on', true);
  WITH doomed AS (SELECT i."tenant_id", i."id" FROM "finding_ingestions" i WHERE i."created_at" < p_cutoff LIMIT p_limit)
  DELETE FROM "finding_ingestions" i USING doomed d WHERE i."tenant_id" = d."tenant_id" AND i."id" = d."id";
  GET DIAGNOSTICS n = ROW_COUNT;
  PERFORM set_config('qm.purge', 'off', true);
  RETURN n;
END;
$$;

