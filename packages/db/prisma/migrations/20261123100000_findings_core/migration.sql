CREATE FUNCTION guard_finding_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW."status" <> 'new' OR NEW."rev" <> 0 THEN
    RAISE EXCEPTION 'INSERT on findings must create status new at rev 0' USING ERRCODE = 'restrict_violation';
  END IF;
