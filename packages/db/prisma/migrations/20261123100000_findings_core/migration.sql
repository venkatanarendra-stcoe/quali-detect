  DELETE FROM "finding_ai_advisories" WHERE "tenant_id" = p_tenant; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "finding_assignments" WHERE "tenant_id" = p_tenant; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "finding_evidence" WHERE "tenant_id" = p_tenant; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "finding_status_history" WHERE "tenant_id" = p_tenant; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
