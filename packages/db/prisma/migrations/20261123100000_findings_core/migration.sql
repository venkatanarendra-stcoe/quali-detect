-- ---- 2. helper functions ---------------------------------------------------------------------------------------------------------
-- The transition table of docs/modules/findings/SPEC.md 6.1, GENERATED from FINDING_TRANSITIONS in @qmentisai/shared (the suite compares
-- every ordered pair of statuses and both actor kinds against the shared constant, FNDA0-06). `from_s` NULL is the creation of a finding.
-- SM-10 (reassignment) is the pair (status, status) for `assigned` and `in_remediation`.
CREATE FUNCTION finding_transition_allowed(from_s "finding_status", to_s "finding_status", actor text) RETURNS boolean LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT EXISTS (
    SELECT 1 FROM (VALUES
    (NULL::text, 'new', 'system'),
    ('new', 'in_review', 'user'),
    ('new', 'awaiting_approval', 'user'),
    ('new', 'fixed_pending_verification', 'system'),
    ('new', 'accepted_risk', 'user'),
    ('new', 'suppressed', 'user'),
    ('in_review', 'awaiting_approval', 'user'),
    ('in_review', 'fixed_pending_verification', 'system'),
    ('in_review', 'accepted_risk', 'user'),
    ('in_review', 'suppressed', 'user'),
    ('awaiting_approval', 'in_review', 'user'),
    ('awaiting_approval', 'approved', 'user'),
    ('awaiting_approval', 'false_positive', 'user'),
    ('awaiting_approval', 'fixed_pending_verification', 'system'),
    ('approved', 'assigned', 'user'),
    ('approved', 'fixed_pending_verification', 'system'),
    ('approved', 'accepted_risk', 'user'),
    ('approved', 'suppressed', 'user'),
    ('false_positive', 'in_review', 'user'),
    ('assigned', 'approved', 'user'),
    ('assigned', 'assigned', 'user'),
    ('assigned', 'in_remediation', 'user'),
    ('assigned', 'fixed_pending_verification', 'user'),
    ('assigned', 'fixed_pending_verification', 'system'),
    ('assigned', 'accepted_risk', 'user'),
    ('assigned', 'suppressed', 'user'),
    ('in_remediation', 'approved', 'user'),
    ('in_remediation', 'in_remediation', 'user'),
    ('in_remediation', 'fixed_pending_verification', 'user'),
    ('in_remediation', 'fixed_pending_verification', 'system'),
    ('in_remediation', 'accepted_risk', 'user'),
    ('in_remediation', 'suppressed', 'user'),
    ('fixed_pending_verification', 'verified_fixed', 'system'),
    ('fixed_pending_verification', 'reopened', 'system'),
    ('verified_fixed', 'reopened', 'system'),
    ('reopened', 'in_review', 'user'),
    ('reopened', 'assigned', 'user'),
    ('reopened', 'fixed_pending_verification', 'system'),
    ('reopened', 'accepted_risk', 'user'),
    ('reopened', 'suppressed', 'user'),
    ('accepted_risk', 'reopened', 'user'),
    ('accepted_risk', 'reopened', 'system'),
    ('suppressed', 'reopened', 'user'),
    ('suppressed', 'reopened', 'system')
    ) AS v(f, t, a)
    WHERE v.f IS NOT DISTINCT FROM from_s::text AND v.t = to_s::text AND v.a = actor)
$$;

-- The actor kind of the current transaction. Fail closed: anything but the explicit setting `system` is a user, so a system-only
-- transition (detect, absent, verified, recurred, expiry) cannot happen by accident. Set by transitionFinding with set_config(..., true).
CREATE FUNCTION qm_finding_actor_type() RETURNS text LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN current_setting('qm.finding_actor_type', true) = 'system' THEN 'system' ELSE 'user' END
$$;

-- True only inside the retention purge functions below (they set `qm.purge` = 'on' for their own transaction).
CREATE FUNCTION qm_purge_active() RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT COALESCE(current_setting('qm.purge', true), '') = 'on'
$$;

-- Generic guards for the immutable history tables.
CREATE FUNCTION finding_forbid_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'UPDATE on % is not allowed: the table is insert-only', TG_TABLE_NAME USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE FUNCTION finding_forbid_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF qm_purge_active() THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION 'DELETE on % is not allowed outside the retention purge', TG_TABLE_NAME USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE FUNCTION finding_forbid_truncate() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'TRUNCATE on % is not allowed', TG_TABLE_NAME USING ERRCODE = 'restrict_violation';
END;
$$;

