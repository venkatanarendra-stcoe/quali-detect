-- ---- 17. the false-positive advisory agent's boundary (SPEC 9.3.4 layer 1; owner decisions 2026-11-23, OQ-6) ------------------------
-- ONE narrow read view. It excludes secret findings ENTIRELY (the agent does not run on them in v1: no snippet, no preview, no
-- metadata ever reaches it), carries no rationale, comment, review, user id, title or fingerprint, and exposes the evidence excerpt
-- only for code findings. The view runs with its owner's rights, so the role needs no privilege on the base tables.
CREATE VIEW "fp_agent_findings" AS
SELECT
  f."tenant_id", f."workspace_id", f."repository_id", f."pipeline_id", f."id", f."rev",
  f."scan_type", f."rule_id", f."rule_name", f."tool_severity", f."severity", f."confidence", f."cwe", f."advisory_ids",
  f."component_name", f."component_version", f."ecosystem", f."fixed_versions", f."path", f."start_line", f."end_line",
  f."last_seen_tools", f."occurrence_count", f."first_detected_at", f."last_seen_at", f."reopen_count", f."origin_trust",
  e."language" AS "evidence_language", e."node_kind" AS "evidence_node_kind", e."kind" AS "evidence_kind", e."start_line" AS "evidence_start_line",
  e."focus_start" AS "evidence_focus_start", e."focus_end" AS "evidence_focus_end", e."snippet" AS "evidence_snippet",
  e."truncated" AS "evidence_truncated", e."captured_at" AS "evidence_captured_at"
FROM "findings" f
LEFT JOIN "finding_evidence" e ON e."tenant_id" = f."tenant_id" AND e."finding_id" = f."id"
WHERE f."scan_type" <> 'secrets';

-- The group role (NOLOGIN). A LOGIN role that is a member of it is provisioned by operations (docs/modules/findings/AS_BUILT_A0.md,
-- packages/db/scripts/provision-fp-agent-login.js) and its connection string is FINDINGS_AGENT_DATABASE_URL. The role gets: SELECT on
-- the view, SELECT and INSERT on finding_ai_advisories, SELECT on tenant_llm_settings (the consent re-check). Nothing else: no UPDATE,
-- no DELETE, no TRUNCATE, no other table. If the migration user may not create roles, the grants are skipped with a NOTICE and the
-- provisioning step creates them (the suite proves the grants on its own cluster, FNDA0-09).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_fp_agent') THEN
    BEGIN
      CREATE ROLE qm_fp_agent NOLOGIN;
    EXCEPTION WHEN insufficient_privilege THEN
      RAISE NOTICE 'qm_fp_agent was not created (insufficient privilege): create it and re-run the GRANTs of this migration (docs/modules/findings/AS_BUILT_A0.md)';
    END;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_fp_agent') THEN
    GRANT SELECT ON "fp_agent_findings" TO qm_fp_agent;
    GRANT SELECT, INSERT ON "finding_ai_advisories" TO qm_fp_agent;
    GRANT SELECT ON "tenant_llm_settings" TO qm_fp_agent;
  END IF;
END
$$;
