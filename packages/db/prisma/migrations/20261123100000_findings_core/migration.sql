END;
$$;

-- The state machine in the database (SPEC 6.3 item 1): the identifying columns never change, `rev` rises by exactly one on every
-- update, and a status change must be one of the allowed transitions for the actor kind of the transaction. A status change without its
-- history row cannot commit (the deferred trigger below).
CREATE FUNCTION guard_finding_update() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  actor text := qm_finding_actor_type();
BEGIN
  IF NEW."id" IS DISTINCT FROM OLD."id" OR NEW."tenant_id" IS DISTINCT FROM OLD."tenant_id" OR NEW."workspace_id" IS DISTINCT FROM OLD."workspace_id"
     OR NEW."repository_id" IS DISTINCT FROM OLD."repository_id" OR NEW."pipeline_id" IS DISTINCT FROM OLD."pipeline_id"
     OR NEW."fingerprint" IS DISTINCT FROM OLD."fingerprint" OR NEW."fp_version" IS DISTINCT FROM OLD."fp_version"
     OR NEW."scan_type" IS DISTINCT FROM OLD."scan_type" OR NEW."kind" IS DISTINCT FROM OLD."kind"
     OR NEW."first_detected_at" IS DISTINCT FROM OLD."first_detected_at" OR NEW."first_execution_id" IS DISTINCT FROM OLD."first_execution_id"
     OR NEW."first_commit_sha" IS DISTINCT FROM OLD."first_commit_sha" OR NEW."created_at" IS DISTINCT FROM OLD."created_at" THEN
    RAISE EXCEPTION 'UPDATE on findings may not change an identifying or first-detection column' USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW."rev" <> OLD."rev" + 1 THEN
    RAISE EXCEPTION 'UPDATE on findings must raise rev by exactly 1 (% to %)', OLD."rev", NEW."rev" USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW."status" IS DISTINCT FROM OLD."status" THEN
    IF NOT finding_transition_allowed(OLD."status", NEW."status", actor) THEN
      RAISE EXCEPTION 'finding transition % to % is not allowed for actor %', OLD."status", NEW."status", actor USING ERRCODE = 'restrict_violation';
    END IF;
    NEW."status_changed_at" := now();
  ELSIF NEW."assignee_user_id" IS DISTINCT FROM OLD."assignee_user_id" AND OLD."status" IN ('assigned', 'in_remediation') THEN
    -- SM-10: the assignee changes, the status stays
    IF NEW."assignee_user_id" IS NULL OR NOT finding_transition_allowed(OLD."status", OLD."status", actor) THEN
      RAISE EXCEPTION 'finding reassignment is not allowed for actor %', actor USING ERRCODE = 'restrict_violation';
    END IF;
  END IF;
  NEW."updated_at" := now();
  RETURN NEW;
END;
$$;

