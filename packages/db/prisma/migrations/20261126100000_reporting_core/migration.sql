JOIN "findings" f ON f."tenant_id" = a."tenant_id" AND f."id" = a."finding_id";

CREATE VIEW "report_executions_v" AS
SELECT
  e."tenant_id", e."workspace_id", e."repository_id", e."pipeline_id", e."id",
  e."status", e."trigger_type", e."ref_type", e."scan_kind", e."trust",
  e."requested_at", e."started_at", e."finished_at", e."created_at",
  r."full_name" AS "repository_name", p."name" AS "pipeline_name", (p."deleted_at" IS NOT NULL) AS "pipeline_deleted",
  (SELECT count(*) FROM "scan_results" s WHERE s."tenant_id" = e."tenant_id" AND s."execution_id" = e."id" AND s."completeness" = 'complete')::integer AS "results_complete",
  (SELECT count(*) FROM "scan_results" s WHERE s."tenant_id" = e."tenant_id" AND s."execution_id" = e."id" AND s."completeness" <> 'complete')::integer AS "results_incomplete",
  EXISTS (SELECT 1 FROM "finding_ingestions" i WHERE i."tenant_id" = e."tenant_id" AND i."execution_id" = e."id" AND i."status" = 'ingested') AS "ingested"
FROM "executions" e
JOIN "pipelines" p ON p."tenant_id" = e."tenant_id" AND p."id" = e."pipeline_id"
JOIN "repositories" r ON r."tenant_id" = e."tenant_id" AND r."id" = e."repository_id";

-- The components of the LATEST SBOM result of each pipeline (any completeness: `result_completeness` says which). No item `data`, no detail row.
CREATE VIEW "report_sbom_latest_v" AS
SELECT
  s."tenant_id", s."workspace_id", s."repository_id", s."pipeline_id", s."execution_id" AS "sbom_execution_id", s."id" AS "sbom_result_id",
  s."completeness" AS "result_completeness", s."created_at" AS "result_created_at",
  i."component_purl", i."component_version", split_part(substr(i."component_purl", 5), '/', 1) AS "ecosystem",
  r."full_name" AS "repository_name", p."name" AS "pipeline_name"
FROM (
  SELECT DISTINCT ON ("tenant_id", "pipeline_id") "tenant_id", "workspace_id", "repository_id", "pipeline_id", "execution_id", "id", "completeness", "created_at"
  FROM "scan_results" WHERE "scan_type" = 'sbom'
  ORDER BY "tenant_id", "pipeline_id", "created_at" DESC, "id" DESC
) s
JOIN "scan_result_items" i ON i."tenant_id" = s."tenant_id" AND i."execution_id" = s."execution_id" AND i."scan_result_id" = s."id" AND i."kind" = 'component'
JOIN "pipelines" p ON p."tenant_id" = s."tenant_id" AND p."id" = s."pipeline_id"
JOIN "repositories" r ON r."tenant_id" = s."tenant_id" AND r."id" = s."repository_id";

