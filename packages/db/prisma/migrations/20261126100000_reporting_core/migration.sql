SELECT t."id" AS "tenant_id", t."status"::text AS "tenant_status", COALESCE(s."reporting_timezone", 'UTC') AS "reporting_timezone"
FROM "tenants" t
LEFT JOIN "tenant_reporting_settings" s ON s."tenant_id" = t."id";

-- ---- 4. purge and clear functions (the roles have no DELETE; SECURITY DEFINER, the pattern of qm_findings_purge_*) ---------------------
-- Clears the daily rollup rows of ONE tenant for an inclusive day range (a rebuild after a time-zone change or a defect fix rebuilds the range
-- from scratch, so a combination that no longer has data disappears: exact, SPEC 7.2).
CREATE FUNCTION qm_reporting_clear_range(p_tenant uuid, p_from date, p_to date) RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE n integer := 0; k integer;
BEGIN
  DELETE FROM "report_daily_findings" WHERE "tenant_id" = p_tenant AND "day" BETWEEN p_from AND p_to; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_daily_executions" WHERE "tenant_id" = p_tenant AND "day" BETWEEN p_from AND p_to; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_daily_decisions" WHERE "tenant_id" = p_tenant AND "day" BETWEEN p_from AND p_to; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_daily_sbom" WHERE "tenant_id" = p_tenant AND "day" BETWEEN p_from AND p_to; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  RETURN n;
END;
$$;

-- Retention (SPEC 8.6): rollup rows older than `p_rollup_before` (a day), rollup runs and export rows older than their cutoffs. Bounded per call.
CREATE FUNCTION qm_reporting_purge(p_rollup_before date, p_runs_before timestamptz, p_exports_before timestamptz, p_limit integer) RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE n integer := 0; k integer;
BEGIN
  DELETE FROM "report_daily_findings" d USING (SELECT "tenant_id", "pipeline_id", "day", "scan_type", "severity" FROM "report_daily_findings" WHERE "day" < p_rollup_before LIMIT p_limit) x
    WHERE d."tenant_id" = x."tenant_id" AND d."pipeline_id" = x."pipeline_id" AND d."day" = x."day" AND d."scan_type" = x."scan_type" AND d."severity" = x."severity"; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_daily_executions" d USING (SELECT "tenant_id", "pipeline_id", "day" FROM "report_daily_executions" WHERE "day" < p_rollup_before LIMIT p_limit) x
    WHERE d."tenant_id" = x."tenant_id" AND d."pipeline_id" = x."pipeline_id" AND d."day" = x."day"; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_daily_decisions" d USING (SELECT "tenant_id", "pipeline_id", "day", "scan_type" FROM "report_daily_decisions" WHERE "day" < p_rollup_before LIMIT p_limit) x
    WHERE d."tenant_id" = x."tenant_id" AND d."pipeline_id" = x."pipeline_id" AND d."day" = x."day" AND d."scan_type" = x."scan_type"; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_daily_sbom" d USING (SELECT "tenant_id", "pipeline_id", "day" FROM "report_daily_sbom" WHERE "day" < p_rollup_before LIMIT p_limit) x
    WHERE d."tenant_id" = x."tenant_id" AND d."pipeline_id" = x."pipeline_id" AND d."day" = x."day"; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_rollup_runs" d USING (SELECT "tenant_id", "id" FROM "report_rollup_runs" WHERE "started_at" < p_runs_before AND "status" <> 'running' LIMIT p_limit) x
    WHERE d."tenant_id" = x."tenant_id" AND d."id" = x."id"; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  DELETE FROM "report_exports" d USING (SELECT "tenant_id", "id" FROM "report_exports" WHERE "created_at" < p_exports_before AND "status" NOT IN ('queued', 'running') LIMIT p_limit) x
    WHERE d."tenant_id" = x."tenant_id" AND d."id" = x."id"; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;
  RETURN n;
END;
$$;

REVOKE ALL ON FUNCTION qm_reporting_clear_range(uuid, date, date) FROM PUBLIC;
REVOKE ALL ON FUNCTION qm_reporting_purge(date, timestamptz, timestamptz, integer) FROM PUBLIC;

-- ---- 5. the two group roles (SPEC 12 item 7, owner ruling of 2026-11-26) -----------------------------------------------------------
-- Both NOLOGIN groups; a LOGIN role that is a member of each is provisioned by operations (packages/db/scripts/provision-reporting-logins.js)
-- and its connection string is REPORTING_DATABASE_URL (qm_reporting, the worker) and REPORTING_RO_DATABASE_URL (qm_reporting_ro, the API reads).
--   qm_reporting_ro: SELECT on the seven views and the six report_* tables. Nothing else. Read-only transactions by default, statement_timeout 5s.
--   qm_reporting:    the same SELECT, plus INSERT and UPDATE on the six report_* tables (no DELETE, no TRUNCATE: rebuilds and retention go through the
--                    two functions above) and EXECUTE on them. NO privilege on ANY source table (findings, evidence, reviews, comments, advisories,
--                    exceptions, history, executions, scan results, tenant_llm_settings, users, ...) and none on any other table.
-- If the migration user may not create roles, the grants are skipped with a NOTICE and the provisioning step creates them (the suite proves the
-- grants on its own cluster, RPTA0).
DO $$
DECLARE v text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting') THEN
    BEGIN
      CREATE ROLE qm_reporting NOLOGIN;
    EXCEPTION WHEN insufficient_privilege THEN
      RAISE NOTICE 'qm_reporting was not created (insufficient privilege): create it and re-run the GRANTs of this migration (docs/modules/reporting-dashboards/AS_BUILT_A0.md)';
    END;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting_ro') THEN
    BEGIN
      CREATE ROLE qm_reporting_ro NOLOGIN;
    EXCEPTION WHEN insufficient_privilege THEN
      RAISE NOTICE 'qm_reporting_ro was not created (insufficient privilege): create it and re-run the GRANTs of this migration (docs/modules/reporting-dashboards/AS_BUILT_A0.md)';
    END;
  END IF;
  FOREACH v IN ARRAY ARRAY['report_findings_v', 'report_status_events_v', 'report_decisions_v', 'report_advisories_v', 'report_executions_v', 'report_sbom_latest_v', 'report_tenant_settings_v'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting') THEN EXECUTE format('GRANT SELECT ON %I TO qm_reporting', v); END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting_ro') THEN EXECUTE format('GRANT SELECT ON %I TO qm_reporting_ro', v); END IF;
  END LOOP;
  FOREACH v IN ARRAY ARRAY['report_daily_findings', 'report_daily_executions', 'report_daily_decisions', 'report_daily_sbom', 'report_rollup_runs', 'report_exports'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting') THEN EXECUTE format('GRANT SELECT, INSERT, UPDATE ON %I TO qm_reporting', v); END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting_ro') THEN EXECUTE format('GRANT SELECT ON %I TO qm_reporting_ro', v); END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting') THEN
    GRANT EXECUTE ON FUNCTION qm_reporting_clear_range(uuid, date, date) TO qm_reporting;
    GRANT EXECUTE ON FUNCTION qm_reporting_purge(date, timestamptz, timestamptz, integer) TO qm_reporting;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qm_reporting_ro') THEN
    ALTER ROLE qm_reporting_ro SET default_transaction_read_only = on;
    ALTER ROLE qm_reporting_ro SET statement_timeout = '5s';
    ALTER ROLE qm_reporting_ro SET idle_in_transaction_session_timeout = '10s';
  END IF;
END
$$;
