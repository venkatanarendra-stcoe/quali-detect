-- ---- 3. the redaction-safe views (SPEC 8.1, ADR-015 item 5): the ONLY way the reporting roles read source data -------------------------
-- Each view runs with its OWNER's rights (the default), so the roles need no privilege on any source table. They expose ids, enums, timestamps,
-- counts, the already-redacted title, rule id, path and line numbers, component fields, severity, status, SLA columns and the repository, pipeline
-- and assignee DISPLAY names. They NEVER expose finding_evidence (snippet, scm_ref, url), finding_reviews.rationale, finding_comments,
-- finding_ai_advisories.reasoning (or its input hash and usage), finding_exceptions.justification and compensating controls, status-history
-- notes, e-mail addresses or any user id other than the assignee id. The suite proves this against information_schema (RPTA0).

CREATE VIEW "report_findings_v" AS
SELECT
  f."tenant_id", f."workspace_id", f."repository_id", f."pipeline_id", f."id",
  f."scan_type", f."kind", f."rule_id", f."title", f."severity", f."severity_rank", f."confidence", f."cwe",
  f."component_purl", f."component_name", f."component_version", f."ecosystem",
  f."path", f."start_line", f."end_line",
  f."status", f."status_changed_at",
  f."assignee_user_id", u."name" AS "assignee_display_name",
  (f."pending_exception_id" IS NOT NULL) AS "exception_pending", f."exception_expires_at",
  -- the cross-pipeline key only for code and component findings (never for a secret: its content key may derive from the secret)
  CASE WHEN f."scan_type" = 'secrets' THEN NULL ELSE f."correlation_key" END AS "correlation_key",
  f."first_detected_at", f."last_seen_at", f."fix_claimed_at", f."verified_at", f."reopened_at", f."reopen_count", f."closed_at",
  f."sla_started_at", f."sla_due_at", f."origin_trust", f."created_at",
  r."full_name" AS "repository_name", p."name" AS "pipeline_name", (p."deleted_at" IS NOT NULL) AS "pipeline_deleted"
FROM "findings" f
JOIN "pipelines" p ON p."tenant_id" = f."tenant_id" AND p."id" = f."pipeline_id"
JOIN "repositories" r ON r."tenant_id" = f."tenant_id" AND r."id" = f."repository_id"
LEFT JOIN "users" u ON u."id" = f."assignee_user_id";

CREATE VIEW "report_status_events_v" AS
SELECT
  h."tenant_id", h."workspace_id", h."repository_id", h."pipeline_id", h."id", h."finding_id", h."rev",
  h."from_status", h."to_status", h."actor_type", h."actor_code", h."reason_code", h."created_at",
  f."scan_type", f."rule_id"
FROM "finding_status_history" h
JOIN "findings" f ON f."tenant_id" = h."tenant_id" AND f."id" = h."finding_id";

-- Review decisions and exception outcomes in ONE timeline: the severity in force at a past instant changes only through an approved review
-- (`severity_override`) or an approved exception (`accepted_severity`), both timestamped here (the as-of reconstruction of ADR-015 item 3).
CREATE VIEW "report_decisions_v" AS
SELECT
  r."tenant_id", r."workspace_id", r."repository_id", r."pipeline_id", r."finding_id", r."id",
  'review'::text AS "source", r."decision", NULL::text AS "exception_kind", r."state",
  r."severity_override", NULL::"finding_severity" AS "accepted_severity", r."advisory_id_at_decision",
  r."created_at", r."decided_at", NULL::timestamptz AS "ended_at", NULL::timestamptz AS "expires_at",
  f."scan_type", f."rule_id"
FROM "finding_reviews" r
JOIN "findings" f ON f."tenant_id" = r."tenant_id" AND f."id" = r."finding_id"
UNION ALL
SELECT
  e."tenant_id", e."workspace_id", e."repository_id", e."pipeline_id", e."finding_id", e."id",
  'exception'::text, NULL::text, e."kind", e."state",
  NULL::"finding_severity", e."accepted_severity", NULL::uuid,
  e."created_at", e."decided_at", e."ended_at", e."expires_at",
  f."scan_type", f."rule_id"
FROM "finding_exceptions" e
JOIN "findings" f ON f."tenant_id" = e."tenant_id" AND f."id" = e."finding_id";

CREATE VIEW "report_advisories_v" AS
