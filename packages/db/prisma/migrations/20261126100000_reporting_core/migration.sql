ALTER TABLE "report_daily_findings" ADD CONSTRAINT "report_daily_findings_values_check" CHECK (
  "day" >= DATE '2000-01-01'
  AND "open_count" >= 0 AND "backlog_count" >= 0 AND "wip_count" >= 0 AND "awaiting_verification_count" >= 0
  AND "sla_on_track" >= 0 AND "sla_due_soon" >= 0 AND "sla_breached" >= 0 AND "exceptions_in_force" >= 0 AND "open_age_seconds_sum" >= 0
  AND "new_count" >= 0 AND "fixed_count" >= 0 AND "closed_other_count" >= 0 AND "reopened_count" >= 0
  -- open = backlog + work in progress (SPEC 5 rule 3); the awaiting-verification share is inside work in progress; the SLA states cover the open ones
  AND "open_count" = "backlog_count" + "wip_count"
  AND "awaiting_verification_count" <= "wip_count"
  AND "sla_on_track" + "sla_due_soon" + "sla_breached" <= "open_count"
);

ALTER TABLE "report_daily_executions" ADD CONSTRAINT "report_daily_executions_values_check" CHECK (
  "day" >= DATE '2000-01-01'
  AND "total" >= 0 AND "succeeded_count" >= 0 AND "failed_count" >= 0 AND "partial_count" >= 0 AND "timed_out_count" >= 0
  AND "cancelled_count" >= 0 AND "skipped_count" >= 0 AND "blocked_count" >= 0
  AND "duration_ms_sum" >= 0 AND "queue_wait_ms_sum" >= 0 AND "eligible_count" >= 0
  AND "result_complete_count" >= 0 AND "result_partial_count" >= 0
  -- queued, running and cancelling executions are in `total` only
  AND "succeeded_count" + "failed_count" + "partial_count" + "timed_out_count" + "cancelled_count" + "skipped_count" + "blocked_count" <= "total"
  AND "eligible_count" <= "total"
);

ALTER TABLE "report_daily_decisions" ADD CONSTRAINT "report_daily_decisions_values_check" CHECK (
  "day" >= DATE '2000-01-01'
  AND "tp_count" >= 0 AND "fp_count" >= 0 AND "with_advisory" >= 0 AND "agree_fp" >= 0 AND "agree_tp" >= 0
  AND "advisory_fp_human_tp" >= 0 AND "advisory_tp_human_fp" >= 0 AND "advisory_uncertain" >= 0 AND "override_confident" >= 0
  AND "with_advisory" <= "tp_count" + "fp_count"
  AND "agree_fp" + "agree_tp" + "advisory_fp_human_tp" + "advisory_tp_human_fp" + "advisory_uncertain" <= "with_advisory"
